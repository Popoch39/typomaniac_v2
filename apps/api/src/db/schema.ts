// Named so the route can tell a Nickname already taken from any other unique violation.
export const nicknameUniqueIndex = "user_nickname_lower_idx";

// Better Auth tables, generated by its `auth` CLI (see the Auth section of apps/api/CLAUDE.md).
// Better Auth looks them up by these export names and column keys: regenerate rather than rename.
// The Nickname column and its index on `user` are the only hand-written parts.

export const user = pgTable(
  "user",
  {
    id: text("id").primaryKey(),
    name: text("name").notNull(),
    email: text("email").notNull().unique(),
    emailVerified: boolean("email_verified").default(false).notNull(),
    image: text("image"),
    createdAt: timestamp("created_at").defaultNow().notNull(),
    updatedAt: timestamp("updated_at")
      .defaultNow()
      .$onUpdate(() => /* @__PURE__ */ new Date())
      .notNull(),
    // Hand-written, not generated: null until the Player chooses their Nickname.
    nickname: text("nickname"),
  },
  // Hand-written too. On the lowercase form so two Nicknames differing only by case collide, while the column keeps the chosen case.
  (table) => [uniqueIndex(nicknameUniqueIndex).on(sql`lower(${table.nickname})`)],
);


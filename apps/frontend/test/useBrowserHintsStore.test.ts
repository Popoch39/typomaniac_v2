import { beforeEach, expect, test } from "bun:test";
import { useBrowserHintsStore } from "../src/features/game/store/useBrowserHintsStore.ts";

beforeEach(() => useBrowserHintsStore.getState().reset());

test("a Game typed on the keyboard hands no scripted key, and tells whether the browser is automated", () => {
  const hints = useBrowserHintsStore.getState();
  hints.countKey(true);
  hints.countKey(true);

  expect(useBrowserHintsStore.getState().take(true)).toEqual({ scriptedKeys: 0, automated: true });
});

test("every key the browser does not flag as trusted counts as generated by a script", () => {
  const hints = useBrowserHintsStore.getState();
  hints.countKey(false);
  hints.countKey(true);
  hints.countKey(false);

  expect(useBrowserHintsStore.getState().take(false)).toEqual({
    scriptedKeys: 2,
    automated: false,
  });
});

test("the hints of a Game are handed once, and again only for the next Game", () => {
  useBrowserHintsStore.getState().countKey(false);

  expect(useBrowserHintsStore.getState().take(false)).toEqual({
    scriptedKeys: 1,
    automated: false,
  });
  expect(useBrowserHintsStore.getState().take(false)).toBeNull();

  useBrowserHintsStore.getState().reset();
  expect(useBrowserHintsStore.getState().take(false)).toEqual({
    scriptedKeys: 0,
    automated: false,
  });
});

// A GitHub or Discord account (its provider and the provider's account id), or an e-mail, that a Ban
// refuses at sign-in for ever, so that a banned Player cannot come back as a new Player with it.
// Kept under the Ban it comes from, so that lifting the Ban lifts them too.
export const bannedIdentity = pgTable(
  "banned_identity",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    sanctionId: uuid("sanction_id")
      .notNull()
      .references(() => sanction.id, { onDelete: "cascade" }),
    // Both set for a provider account, both null for an e-mail.
    providerId: text("provider_id"),
    accountId: text("account_id"),
    // Lowercase, as addresses are compared at sign-in.
    email: text("email"),
  },
  (table) => [
    check(
      "banned_identity_one_kind",
      sql`(${table.providerId} is null) = (${table.accountId} is null) and (${table.accountId} is null) <> (${table.email} is null)`,
    ),
    index("banned_identity_account_idx").on(table.providerId, table.accountId),
    index("banned_identity_email_idx").on(table.email),
    index("banned_identity_sanction_idx").on(table.sanctionId),
  ],
);


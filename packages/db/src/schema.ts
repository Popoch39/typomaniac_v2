// One row per seat of a Round, with the full journal so that the Game can be replayed and audited.
export const duelGame = pgTable(
  "duel_game",
  {
    duelId: uuid("duel_id").notNull(),
    round: smallint("round").notNull(),
    seat: smallint("seat").$type<Seat>().notNull(),
    result: jsonb("result").$type<Result>().notNull(),
    journal: jsonb("journal").$type<GameEvent[]>().notNull(),
    // The Outcome of the Round for this seat.
    outcome: text("outcome", { enum: ["win", "loss", "draw"] })
      .$type<Outcome>()
      .notNull(),
    // The average Multiplier the server judged the Game with: the Result does not hold what each
    // word was. A Game saved before the Multiplier reads as ×1, and its Outcome stays as judged.
    multiplier: doublePrecision("multiplier").notNull().default(1),
    // What the browser told of how the Game was typed, a signal of the Suspicion (ADR 0014); null
    // when its client sent none, and always in a Custom Duel.
    hints: jsonb("hints").$type<BrowserHints>(),
  },
  (table) => [
    primaryKey({ columns: [table.duelId, table.round, table.seat] }),
    foreignKey({
      columns: [table.duelId, table.round],
      foreignColumns: [duelRound.duelId, duelRound.round],
    }).onDelete("cascade"),
  ],
);

// One row per seat of a Duel: who sat there and what the Duel meant for them. The columns after the
// Outcome are those of a ranked Duel, all null for a Custom Duel: the Player's Standing before and
// after it, stored as in `standing`, so that a change of Rank can be explained and audited.
export const duelParticipant = pgTable(
  "duel_participant",
  {
    duelId: uuid("duel_id")
      .notNull()
      .references(() => duel.id, { onDelete: "cascade" }),
    seat: smallint("seat").$type<Seat>().notNull(),
    // Null for a Guest, who leaves no trace: the seat stays as the one of an unnamed Opponent.
    playerId: text("player_id").references(() => user.id, { onDelete: "set null" }),
    // The Outcome of the Duel for this seat.
    outcome: text("outcome", { enum: ["win", "loss", "draw"] })
      .$type<Outcome>()
      .notNull(),
    mmrBefore: integer("mmr_before"),
    mmrAfter: integer("mmr_after"),
    duelsPlayedBefore: integer("duels_played_before"),
    duelsPlayedAfter: integer("duels_played_after"),
    ladderIndexBefore: smallint("ladder_index_before"),
    lpBefore: integer("lp_before"),
    ladderIndexAfter: smallint("ladder_index_after"),
    lpAfter: integer("lp_after"),
    // The LP won or lost, signed.
    lpDelta: integer("lp_delta"),
    rankChange: text("rank_change", {
      enum: ["placed", "promoted", "demoted", "none"],
    }).$type<RankChange>(),
  },
  (table) => [
    primaryKey({ columns: [table.duelId, table.seat] }),
    // A Player's ranked Duels in the order they played them, for the Outcomes of their Placement.
    index("duel_participant_player_idx").on(table.playerId, table.duelsPlayedBefore),
  ],
);

// One row per Violation refused live in a ranked Duel (ADR 0014, ADR 0016), counted per Player to
// pick their automatic Sanction. Written as it is refused, before the Duel is saved: no key to `duel`.
export const violation = pgTable(
  "violation",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    playerId: text("player_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    duelId: uuid("duel_id").notNull(),
    round: smallint("round").notNull(),
    kind: text("kind", { enum: ["multipleCharacters", "noKeyPress"] })
      .$type<ViolationKind>()
      .notNull(),
    committedAt: timestamp("committed_at").defaultNow().notNull(),
    // When the fair-play pass sanctioned it, once its Duel was saved; null until then.
    sanctionedAt: timestamp("sanctioned_at"),
    // The Sanction of the step of the ladder it brought; null until it is sanctioned. A Violation
    // counts towards the next one's Sanction while that Sanction is not revoked, even when its own
    // Duel was not voided.
    sanctionId: uuid("sanction_id").references(() => sanction.id, { onDelete: "set null" }),
  },
  (table) => [index("violation_player_idx").on(table.playerId, table.duelId)],
);

// What the signals said of one saved ranked Game (ADR 0014), with the version of the signals that

// A Player's Suspicion, as the fair-play pass last computed it from their recent ranked Games, and the
// instant it did. It never sanctions: past a threshold it only calls for a Review.
export const suspicion = pgTable("suspicion", {
  playerId: text("player_id")
    .primaryKey()
    .references(() => user.id, { onDelete: "cascade" }),
  value: doublePrecision("value").notNull(),
  // What the signals across the Player's recent ranked Duels said. A Suspicion computed before they
  // existed reads none of them, until the raised version of the signals has it computed again.
  duelSignals: jsonb("duel_signals").$type<DuelSignals>().notNull().default({
    levelJump: 0,
    errorlessSeries: 0,
    oneSidedPair: 0,
    lossWithoutTyping: 0,
    reports: 0,
  }),
  computedAt: timestamp("computed_at").notNull(),
});

// A Player's statement, made at the end of a ranked Duel, that their Opponent cheated in it (ADR 0014).
// It never sanctions: it only raises the reported Player's Suspicion, and they are told nothing of it.
// One per Duel and reporting Player.
export const report = pgTable(
  "report",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    duelId: uuid("duel_id")
      .notNull()
      .references(() => duel.id, { onDelete: "cascade" }),
    reporterId: text("reporter_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    reportedId: text("reported_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    reportedAt: timestamp("reported_at").notNull(),
  },
  (table) => [
    uniqueIndex("report_duel_reporter_idx").on(table.duelId, table.reporterId),
    // The Reports against a Player, read by the fair-play pass and by their Review.
    index("report_reported_idx").on(table.reportedId, table.reportedAt),
  ],
);

// A person's examination of a Player (ADR 0014), opened by the fair-play pass for a reason, open until
// it is settled with a decision. At most one is open per Player, and reaching Master or the Podium
// opens one once: both held by unique indexes as well as by the pass.
export const review = pgTable(
  "review",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    playerId: text("player_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    reason: text("reason", { enum: ["suspicion", "master", "podium"] })
      .$type<ReviewReason>()
      .notNull(),
    openedAt: timestamp("opened_at").notNull(),
    // Both null while the Review is open. After a settling, only the Games played after it count
    // towards a new Review by Suspicion.
    settledAt: timestamp("settled_at"),
    decision: text("decision", { enum: ["cleared", "voided_duels", "suspension", "ban"] }),
  },
  (table) => [
    check("review_settled_whole", sql`(${table.settledAt} is null) = (${table.decision} is null)`),
    uniqueIndex("review_open_player_idx")
      .on(table.playerId)
      .where(sql`${table.settledAt} is null`),
    uniqueIndex("review_rank_reason_idx")
      .on(table.playerId, table.reason)
      .where(sql`${table.reason} <> 'suspicion'`),
  ],
);

// A Sanction applied to a Player for cheating, in rising order: a Voided Duel, a Suspension, a Ban.
// Its cause says whether a Violation or a Review brought it. Kept once revoked, so that a Player's
// history stays whole.
export const sanction = pgTable(
  "sanction",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    playerId: text("player_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    kind: text("kind", { enum: ["voided_duel", "suspension", "ban"] }).notNull(),
    cause: text("cause", { enum: ["violation", "review"] }).notNull(),
    startedAt: timestamp("started_at").notNull(),
    // The end of a Suspension; null for the other kinds.
    endsAt: timestamp("ends_at"),
    revokedAt: timestamp("revoked_at"),
  },
  (table) => [index("sanction_player_idx").on(table.playerId)],
);

